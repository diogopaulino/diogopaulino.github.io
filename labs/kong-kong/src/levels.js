/**
 * Mapas em ASCII. Cada caractere = 1 tile (16px).
 *
 * . vazio   # terra   = grama sólida   - plataforma one-way
 * ^ espinhos   ~ água   | cipó   @ caixa   * caixa (quebra no rolamento)
 * S spawn   X saída   H checkpoint (barril K)
 * b banana   u cacho (10)   1 balão 1-up
 * K O N G letras
 * e lagarto   f zangão   p ouriço (não pisa — role)
 * B barril de madeira   C canhão →   Q canhão ↗   U canhão ↑   L canhão ←
 * T TNT   o mola   M plataforma móvel   W Rei Croco
 */

function pack(name, theme, title, hint, rows) {
  const map = rows.map((r) => r);
  const w = Math.max(...map.map((r) => r.length));
  const padded = map.map((r) => r.padEnd(w, '.'));
  return { name, theme, title, hint, map: padded, w, h: padded.length };
}

